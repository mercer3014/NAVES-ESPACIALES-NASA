import assert from 'node:assert/strict';
import { trackFov, sideAxis, chaseStand, trackStand, sphereOccludes } from '../src/game/launch-camera.js';

const far = trackFov(14140);
assert.equal(far, 12, '14 km telephoto stays wide enough to keep sky and vehicle');
assert.equal(trackFov(2000), 12);
assert.ok(trackFov(600) > 16);
assert.equal(trackFov(80), 42);
const [sx, sy, sz] = sideAxis(0, 1, 0);
assert.ok(Math.abs(sy) < 1e-6, 'vertical rocket: camera side is horizontal, not down the plume');
assert.ok(Math.abs(sx * 0 + sy * 1 + sz * 0) < 1e-6);
const pitched = sideAxis(0.3, 0.95, -0.1);
const dot = pitched[0] * 0.3 + pitched[1] * 0.95 + pitched[2] * -0.1;
assert.ok(Math.abs(dot) < 1e-6, dot);
const chase = chaseStand(false), staging = chaseStand(true), track = trackStand();
assert.ok(chase.lateral > 80 && chase.along > 0, 'chase stays beside the stack, not down the plume');
assert.ok(staging.lateral > chase.lateral && staging.along > 0, 'staging opens up so the falling stage stays in frame');
assert.ok(track.lateral > 400 && track.lateral < 4000 && track.along > 0, 'track lens stays close enough to read the airframe');
assert.equal(sphereOccludes(0, 0, 0, 0, 10, 0, 0, 5, 0, 2), true);
assert.equal(sphereOccludes(0, 0, 0, 0, 10, 0, 30, 5, 0, 2), false);
assert.equal(sphereOccludes(0, 5, 0, 0, 10, 0, 0, 5, 0, 3), true, 'camera inside the shell');
console.log('PASS launch cameras', { far, side: [sx, sy, sz] });
