export function playChain(files, { radio = false, i = 0 } = {}) {
  if (typeof window === 'undefined' || commsMode() === 'off') return null;
  const id = files?.[i]; if (!id) return null;
  const file = CLIP[id] || id;
  if (radio && i === 0) quindar('in');
  const h = playA11(file);
  if (!h) return null;
  showRadioSub(file, h);
  const last = i >= files.length - 1;
  h.once('end', () => {
    if (last && radio) quindar('out');
    else if (!last) setTimeout(() => playChain(files, { radio: false, i: i + 1 }), 160);
  });
  return h;
}

export function clip(id, opts) { return playChain([id], opts || {}); }
export function clips(ids, opts) { return playChain(ids, opts || {}); }

